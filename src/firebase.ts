export function isVerifiedOwnerUser(user: User | null): boolean {
  if (!user) return false;
  return (
    user.emailVerified === true &&
    (user.email || '').toLowerCase() === OWNER_ADMIN_EMAIL.toLowerCase()
  );
}

export async function signInOwnerWithGoogle(): Promise<User> {
  const cred = await signInWithPopup(auth, googleProvider);
  return cred.user;
}

export async function signOutOwner(): Promise<void> {
  await signOut(auth);
}

export function subscribeOwnerAuth(callback: (user: User | null) => void) {
  return onAuthStateChanged(auth, callback);
}
